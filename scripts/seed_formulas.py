def seed_formulas() -> int:
    """Idempotently seed the GATE Formula and Shortcut Library across all 5 branches."""
    created = 0
    branches = {b.code: b for b in Branch.query.all()}
    for b_code, s_code, title, latex, vars_md, shortcut, tip in FORMULAS:
        target_branches = list(branches.values()) if b_code == "ALL" else ([branches[b_code]] if b_code in branches else [])
        for branch in target_branches:
            if FormulaEntry.query.filter_by(branch_id=branch.id, title=title).first():
                continue
            sv = resolve_syllabus_version(branch.id, 2026)
            subj = Subject.query.filter_by(syllabus_version_id=sv.id, code=s_code).first() if sv else None
            db.session.add(
                FormulaEntry(
                    branch_id=branch.id,
                    subject_id=subj.id if subj else None,
                    title=title,
                    formula_latex=latex,
                    variables_md=vars_md,
                    shortcut_md=shortcut,
                    exam_tip_md=tip,
                )
            )
            created += 1
    db.session.commit()
    return created
